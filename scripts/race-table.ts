// Writes src/math/raceTable.ts: the fairest rotation race chart for 2–8 lanes
// and up to 60 cars, from the exhaustive search in src/math/raceSearch.ts.
// Run with Node 24 or newer (about half a minute): node scripts/race-table.ts

import { writeFileSync } from 'node:fs';
import { fairestRotation } from '../src/math/raceSearch.ts';

const MAX_LANES = 8;
const MAX_CARS = 60;

const rows: string[] = [];
for (let lanes = 2; lanes <= MAX_LANES; lanes++) {
  for (let cars = lanes + 1; cars <= MAX_CARS; cars++) {
    const { set, lo, hi } = fairestRotation(lanes, cars);
    rows.push(`  { lanes: ${lanes}, cars: ${cars}, lo: ${lo}, hi: ${hi}, set: [${set.join(', ')}] },`);
  }
}

const text = `// Generated by scripts/race-table.ts; do not edit by hand.
//
// For each number of lanes and cars, the heat-0 lineup D of the fairest
// rotation chart: every two cars meet between lo and hi times, and no D does
// better (a narrower window, or the same width with a smaller hi).

export interface RaceEntry {
  lanes: number;
  cars: number;
  lo: number;
  hi: number;
  set: number[];
}

export const RACE_MAX_LANES = ${MAX_LANES};
export const RACE_MAX_CARS = ${MAX_CARS};

export const RACE_TABLE: readonly RaceEntry[] = [
${rows.join('\n')}
];
`;
writeFileSync(new URL('../src/math/raceTable.ts', import.meta.url), text);
console.log(`Wrote ${rows.length} charts.`);
